export type TransactionStatus = 'PENDING' | 'COMPLETED' | 'FAILED' | 'REJECTED';

export type AccountStatus = 'ACTIVE' | 'SUSPENDED' | 'PENDING_VERIFICATION';

export type Currency = 'USD' | 'EUR' | 'GBP' | 'BTC' | 'ETH' | 'USDT' | 'USDC';

/**
 * Represents a B2B entity/account participating in the cryptographic audit trail system.
 */
export interface B2BAccount {
  id: string;
  companyName: string;
  taxId: string;
  email: string;
  publicKey: string; // PEM or Hex encoded public key used for verifying transaction signatures
  status: AccountStatus;
  createdAt: string; // ISO 8601 string
  updatedAt: string; // ISO 8601 string
}

/**
 * Represents a single transaction between two B2B accounts.
 * This payload is cryptographically signed by the sender.
 */
export interface B2BTransaction {
  id: string;
  senderId: string;
  receiverId: string;
  amount: number;
  currency: Currency;
  timestamp: string; // ISO 8601 string
  reference: string; // e.g., Invoice ID, Purchase Order ID
  status: TransactionStatus;
  signature: string; // Cryptographic signature of the transaction payload generated by the sender's private key
  metadata?: Record<string, any>; // Optional structured metadata (e.g., line items, tax details)
}

/**
 * Represents a block in the cryptographic audit trail ledger.
 * Blocks are chained together using SHA-256 hashes.
 */
export interface AuditBlock {
  index: number;
  timestamp: string; // ISO 8601 string
  transactions: B2BTransaction[];
  previousHash: string; // SHA-256 hash of the previous block
  hash: string; // SHA-256 hash of the current block (index + timestamp + transactions + previousHash + nonce + merkleRoot)
  merkleRoot: string; // Merkle root hash of the transactions in this block
  nonce: number; // Proof-of-work or consensus nonce
  validatorSignature: string; // Signature of the block hash by the system's validator/auditor node
  validatorPublicKey: string; // Public key of the validator that sealed this block
}

/**
 * Summary statistics for a specific audit report.
 */
export interface ReportSummary {
  totalTransactions: number;
  totalVolumeByCurrency: Partial<Record<Currency, number>>;
  activeAccountsCount: number;
  tamperCheckPassed: boolean;
}

/**
 * Represents a cryptographically signed audit report generated for compliance or internal review.
 */
export interface SignedAuditReport {
  reportId: string;
  generatedAt: string; // ISO 8601 string
  dateRange: {
    start: string; // ISO 8601 string
    end: string; // ISO 8601 string
  };
  blockRange: {
    startBlockIndex: number;
    endBlockIndex: number;
  };
  summary: ReportSummary;
  reportHash: string; // SHA-256 hash of the report content (excluding signature)
  signature: string; // Cryptographic signature of the reportHash by the generating authority
  signerPublicKey: string; // Public key of the authority that signed the report
  signerIdentity: string; // Name/Identifier of the signing authority (e.g., "Internal Audit Dept", "External Auditor Corp")
}

/**
 * Result structure for cryptographic verification of the audit trail.
 */
export interface AuditVerificationResult {
  isValid: boolean;
  totalBlocksChecked: number;
  tamperedBlockIndices: number[];
  invalidTransactionIds: string[];
  verificationChain: {
    blockIndex: number;
    hashVerified: boolean;
    signatureVerified: boolean;
    previousHashMatched: boolean;
  }[];
  verifiedAt: string; // ISO 8601 string
}